// ══════════════════════════════════════════════════════════════════════
// [MainController = 사이트의 "입구" 주소를 담당하는 창구] (v2.08 갱신)
// ══════════════════════════════════════════════════════════════════════
//
// 이 클래스는 두 주소를 맡습니다.
//   1) /sbb  → 연습용 글자 한 줄을 그대로 보여 줍니다. (화면 파일 없이 글자만 응답)
//   2) /     → 사이트의 첫 주소입니다. 질문 목록 화면으로 "다시 가라"고 안내합니다. (redirect)
//
// ── 반환값을 스프링이 해석하는 세 가지 방식 (이 클래스에서 모두 나옵니다) ──────
//   ① @ResponseBody 가 있다 → 돌려준 글자를 그대로 응답 본문에 넣습니다. (화면 파일을 찾지 않음)
//   ② @ResponseBody 가 없다 → 돌려준 글자를 "화면 이름"으로 보고 templates/이름.html 을 그립니다.
//   ③ "redirect:주소" 이다 → 화면을 그리지 않고, 브라우저에게 "그 주소로 새로 요청하라"고 응답합니다.
//
// ── 자주 헷갈리는 점 ───────────────────────────────────────────────────
//   · 이 클래스에는 DB(SQL)가 전혀 없습니다. 주소를 받아서 화면을 바꾸는 일만 합니다.
//   · @Controller 는 "웹 창구"라는 뜻이고, @Service 나 @Repository 와는 역할이 다릅니다.
// ══════════════════════════════════════════════════════════════════════
package com.mysite.sbb;

// [@Controller 꼬리표 가져오기] 이 클래스가 웹 요청을 받는 창구라는 표시를 붙일 때 씁니다.
import org.springframework.stereotype.Controller;
// [@GetMapping 꼬리표 가져오기] GET 방식 요청의 주소와 메서드를 연결합니다.
import org.springframework.web.bind.annotation.GetMapping;
// [@ResponseBody 꼬리표 가져오기] 메서드가 돌려준 값을 "화면 이름"이 아니라 "응답 내용 그대로" 보내게 합니다.
import org.springframework.web.bind.annotation.ResponseBody;

// ─ 웹 창구 표시 ─
// 스프링이 시작할 때 이 클래스의 객체를 만들어 보관하고(Bean 등록), 요청이 오면 맞는 메서드를 실행합니다.
@Controller
// 메인 화면과 연습용 주소를 담당하는 창구 클래스입니다.
public class MainController {

	// ─ 주소 연결: /sbb ─
	// [GET /sbb] 브라우저가 http://localhost:8070/sbb 로 GET 요청을 보내면 아래 index() 가 실행됩니다.
	//   · 주소 뒤쪽 /sbb 가 메서드와 짝지어지는 이름표입니다.
	@GetMapping("/sbb")
	// ─ 응답 방식 표시 ─
	// 이 꼬리표가 있으므로 index() 가 돌려준 글자가 "화면 이름"이 아니라 "응답 내용"이 됩니다.
	// 없었다면 스프링은 "안녕하세요 sbb에 오신것을 환영합니다." 라는 이름의 HTML 파일을 찾다가 오류가 납니다.
	@ResponseBody
	// ─ index() 메서드 ─
	// 돌려주는 글자가 브라우저 화면에 그대로 보이는 가장 단순한 메서드입니다.
	// 메서드 이름 index 는 "사이트의 기본(첫) 화면"을 뜻하는 관례적인 이름입니다.
	public String index() {
		// ─ 돌려줄 글자 ─
		// 큰따옴표 안의 글자가 그대로 응답 본문이 됩니다. 한글도 그대로 쓸 수 있습니다.
		// (앞 버전에서는 "오신 것을"이었지만 이번 단계에서 띄어쓰기를 "오신것을"로 바꾸었습니다. 실행 결과 글자가 달라집니다)
		return "안녕하세요 sbb에 오신것을 환영합니다.";
	}

	// ─ 주소 연결: / (사이트 첫 주소) ─
	// [GET /] 주소 뒤에 아무것도 없이 들어왔을 때 실행됩니다. (예: http://localhost:8070/)
	//   · 이 메서드에는 @ResponseBody 가 없습니다. 그래서 반환값은 "화면 이름" 또는 "redirect:" 규칙으로 해석됩니다.
	@GetMapping("/")
	// ─ root() 메서드 ─
	// "루트(뿌리) 주소" 담당 메서드입니다. 이 메서드는 화면을 직접 그리지 않고, 다른 주소로 보내는 일만 합니다.
	public String root() {
		// ─ redirect: 의 동작 원리 ─
		//   · "redirect:" 로 시작하면 스프링은 화면을 그리지 않고 브라우저에게 "302 응답"을 보냅니다.
		//   · 302 응답에는 "이 주소(/question/list)로 새로 GET 요청을 해라"라는 Location 정보가 들어 있습니다.
		//   · 브라우저는 그 말을 듣고 /question/list 로 한 번 더 요청합니다. 그래서 주소창도 /question/list 로 바뀝니다.
		//   · 서버 안에서 몰래 넘기는 "forward"와 달리, 브라우저가 직접 두 번째 요청을 보냅니다. (그래서 "redirect" 라고 부릅니다)
		//
		// 흐름 한눈에 보기
		//   브라우저: GET /        →  MainController.root()  →  302 + Location: /question/list
		//   브라우저: GET /question/list (자동)  →  QuestionController.list()  →  질문 목록 화면
		return "redirect:/question/list";
	}
}
